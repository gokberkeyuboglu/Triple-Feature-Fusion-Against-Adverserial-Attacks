def train_detector(model, loader, optimizer, epochs, name):
    print(f"\nTraining {name} ({epochs} epochs)...")
    model.train()
    for epoch in range(epochs):
        for batch in loader:
            *features, lbls = [b.to(DEVICE) for b in batch]
            optimizer.zero_grad()
            out = model(*features)
            F.cross_entropy(out, lbls).backward()
            optimizer.step()
        if (epoch + 1) % max(1, epochs // 2) == 0:
            print(f"  {name} epoch {epoch+1}/{epochs}")


