def eval_all_detectors(loader):
    counts = {
        "std":    [0, 0, 0],
        "srm":    [0, 0, 0],
        "wave":   [0, 0, 0],
        "triple": [0, 0, 0],
    }
    total = 0

    for batch_i, (imgs, lbls) in enumerate(loader):
        imgs, lbls = imgs.to(DEVICE), lbls.to(DEVICE)
        imgs_01 = torch.clamp(imgs * STD_T + MEAN_T, 0, 1)

        adv_01  = pgd_attack(base_model, imgs_01, lbls)
        adv2_01 = second_round_attack(base_model, detector, imgs_01, lbls)
        total  += lbls.size(0)

        # SRM features
        srm_c  = torch.from_numpy(srm_features(imgs_01.cpu().numpy())[:, srm_idx]).float().to(DEVICE)
        srm_a  = torch.from_numpy(srm_features(adv_01.cpu().numpy())[:, srm_idx]).float().to(DEVICE)
        srm_a2 = torch.from_numpy(srm_features(adv2_01.cpu().numpy())[:, srm_idx]).float().to(DEVICE)

        # Wavelet features
        wv_c  = compute_haar_features(imgs_01)
        wv_a  = compute_haar_features(adv_01)
        wv_a2 = compute_haar_features(adv2_01)

        with torch.no_grad():
            # Standard
            counts["std"][0] += detector(imgs_01).argmax(1).eq(0).sum().item()
            counts["std"][1] += detector(adv_01).argmax(1).eq(1).sum().item()
            counts["std"][2] += detector(adv2_01).argmax(1).eq(1).sum().item()

            # SRM Fusion
            counts["srm"][0] += detector_fusion(imgs_01, srm_c).argmax(1).eq(0).sum().item()
            counts["srm"][1] += detector_fusion(adv_01, srm_a).argmax(1).eq(1).sum().item()
            counts["srm"][2] += detector_fusion(adv2_01, srm_a2).argmax(1).eq(1).sum().item()

            # Wavelet Fusion
            counts["wave"][0] += detector_wavelet(imgs_01, wv_c).argmax(1).eq(0).sum().item()
            counts["wave"][1] += detector_wavelet(adv_01, wv_a).argmax(1).eq(1).sum().item()
            counts["wave"][2] += detector_wavelet(adv2_01, wv_a2).argmax(1).eq(1).sum().item()

            # Triple Fusion
            counts["triple"][0] += detector_triple(imgs_01, wv_c, srm_c).argmax(1).eq(0).sum().item()
            counts["triple"][1] += detector_triple(adv_01, wv_a, srm_a).argmax(1).eq(1).sum().item()
            counts["triple"][2] += detector_triple(adv2_01, wv_a2, srm_a2).argmax(1).eq(1).sum().item()

        if (batch_i + 1) % 10 == 0:
            print(f"  Evaluated {batch_i+1}/{len(loader)} batches...")

    accs = {k: [100. * v / total for v in vals] for k, vals in counts.items()}
    return accs, total


